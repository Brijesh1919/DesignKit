/**
 * Checks whether a word is a valid English word or standard morphological derivation
 * (regular plurals -s/-es/-ies, past tense -ed/-d, gerund -ing, etc.).
 */
export function isValidEnglishWord(rawWord: string): boolean {
  if (!rawWord) return false
  const word = rawWord.toLowerCase().replace(/['’]s$/, '')
  if (word.length <= 1) return true
  if (VALID_WORDS.has(word)) return true

  // Regular plurals or 3rd person singular (-s)
  if (word.endsWith('s')) {
    if (VALID_WORDS.has(word.slice(0, -1))) return true
    if (word.endsWith('es') && VALID_WORDS.has(word.slice(0, -2))) return true
    if (word.endsWith('ies') && VALID_WORDS.has(word.slice(0, -3) + 'y')) return true
  }

  // Past tense / past participle (-ed, -d)
  if (word.endsWith('ed')) {
    if (VALID_WORDS.has(word.slice(0, -2))) return true
    if (VALID_WORDS.has(word.slice(0, -1))) return true
    if (word.endsWith('ied') && VALID_WORDS.has(word.slice(0, -3) + 'y')) return true
  }

  // Gerund / participle (-ing)
  if (word.endsWith('ing')) {
    if (VALID_WORDS.has(word.slice(0, -3))) return true
    if (VALID_WORDS.has(word.slice(0, -3) + 'e')) return true
  }

  // Adverb (-ly)
  if (word.endsWith('ly')) {
    if (VALID_WORDS.has(word.slice(0, -2))) return true
    if (word.endsWith('ily') && VALID_WORDS.has(word.slice(0, -3) + 'y')) return true
  }

  return false
}

